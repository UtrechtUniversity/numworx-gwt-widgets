package fi.nabouwenaanzichtengwt.client;

/**
 * klasse die een hoekpunt van een 3d-figuur representeert;
 * de klasse bevat de 3d-coordinaten van het hoekpunt.   
 * @author Peter Boon
 */
public class Hoekpunt 
{	double x,y,z;

	public Hoekpunt(double x, double y, double z)
	{	this.x = x;
		this.y = y;
		this.z = z;
	}
}